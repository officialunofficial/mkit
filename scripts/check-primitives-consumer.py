#!/usr/bin/env python3
"""Out-of-tree consumer of mkit-primitives, built from packaged crates only.

Default (rehearsal) mode packages mkit-ruzstd, mkit-core and mkit-primitives
with `cargo package`, extracts the three `.crate` files into a directory source
that replaces crates.io for a standalone consumer, and runs the consumer's
fixture tests natively and on wasm32. The consumer has no path dependency, no
`[patch]` table and no workspace membership. It reads the portable fixtures from
the extracted package, so it proves what ships, using only the published API.

`--registry VERSION` is the post-publication smoke: the same consumer resolved
from crates.io with no overlay at all.

Nothing is published or uploaded.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
RUST = ROOT / "rust"
CONSUMER_SOURCE = ROOT / "scripts/primitives-consumer"
RUZSTD_MANIFEST = RUST / "vendor/ruzstd/Cargo.toml"
OVERLAY = ("mkit-ruzstd", "mkit-core", "mkit-primitives")


def run(command, cwd, env=None, **kwargs):
    print("+", " ".join(str(part) for part in command), flush=True)
    subprocess.run(command, cwd=cwd, env=env, check=True, **kwargs)


def cargo_home():
    return Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo"))


def third_party_closure():
    """Every locked registry package, as (name, version, directory, checksum).

    Packaging a workspace member resolves the whole workspace, so the overlay
    carries the full lockfile rather than one crate's closure.
    """
    run(["cargo", "fetch", "--locked"], cwd=RUST)
    lock = tomllib.loads((RUST / "Cargo.lock").read_text())["package"]
    seen = {(p["name"], p["version"]): p for p in lock}
    result = []
    for (name, version), package in sorted(seen.items()):
        if "source" not in package:
            continue
        found = sorted((cargo_home() / "registry/src").glob(f"*/{name}-{version}"))
        if not found:
            raise SystemExit(f"{name} {version}: fetched source not found")
        result.append((name, version, found[0], package.get("checksum")))
    return result


def write_checksum(directory, checksum):
    (directory / ".cargo-checksum.json").write_text(
        json.dumps({"files": {}, "package": checksum}))


def seed_directory_source(vendor):
    count = 0
    for name, version, source, checksum in third_party_closure():
        target = vendor / f"{name}-{version}"
        shutil.copytree(source, target)
        write_checksum(target, checksum)
        count += 1
    return count


def replacement_config(vendor):
    return (
        "[source.crates-io]\nreplace-with = \"packaged\"\n\n"
        f"[source.packaged]\ndirectory = \"{vendor}\"\n\n"
        "[net]\noffline = true\n"
    )


def package(name, manifest, vendor, target):
    """Package one crate against the overlay, then extract it into the overlay."""
    command = ["cargo", "package", "--no-verify", "--allow-dirty",
               "--target-dir", str(target / "package")]
    if manifest is None:
        # Workspace members resolve their registry dependencies from the overlay.
        config = Path(tempfile.mkdtemp(prefix="package-config-", dir=target)) / "config.toml"
        config.write_text(replacement_config(vendor))
        command[1:1] = ["--config", str(config)]
        command += ["--offline", "-p", name]
    else:
        # The standalone decoder is its own manifest: it resolves against the
        # real index, exactly as the release script packages it.
        command += ["--manifest-path", str(manifest)]
    run(command, cwd=RUST)
    crates = list((target / "package/package").glob(f"{name}-*.crate"))
    if len(crates) != 1:
        raise SystemExit(f"expected one packaged {name} crate, found {len(crates)}")
    data = crates[0].read_bytes()
    stem = crates[0].name.removesuffix(".crate")
    with tarfile.open(crates[0]) as archive:
        archive.extractall(vendor, filter="data")
    write_checksum(vendor / stem, hashlib.sha256(data).hexdigest())
    shutil.rmtree(target / "package/package")
    return vendor / stem


def embedded_module(fixtures):
    """Generate the fixture table compiled into the consumer, for native and wasm."""
    lines = ["// Generated by scripts/check-primitives-consumer.py; not committed.\n",
             "pub static ACCEPTANCE: &[(&str, &[u8], &str)] = &[\n"]
    for case in sorted((fixtures / "acceptance").glob("*.json")):
        stem = case.stem
        lines.append(
            f'    ("{stem}", include_bytes!("../fixtures/acceptance/{stem}.bin"), '
            f'include_str!("../fixtures/acceptance/{stem}.json")),\n')
    lines.append("];\n")
    if len(lines) == 2:
        raise SystemExit("consumer: acceptance fixtures missing from the package")
    return "".join(lines)


def download_published(version, work):
    """Fetch and extract the published crate, returning its directory."""
    from urllib.request import Request, urlopen
    url = f"https://crates.io/api/v1/crates/mkit-primitives/{version}/download"
    request = Request(url, headers={"User-Agent": "mkit-release (primitives consumer)"})
    with urlopen(request, timeout=120) as response:
        data = response.read()
    archive = work / "published.crate"
    archive.write_bytes(data)
    with tarfile.open(archive) as tar:
        tar.extractall(work, filter="data")
    return work / f"mkit-primitives-{version}"


def build_consumer(work, vendor, primitives_dir, registry):
    consumer = work / "consumer"
    shutil.copytree(CONSUMER_SOURCE, consumer)
    shutil.copytree(primitives_dir / "fixtures", consumer / "fixtures")
    if not registry:
        (consumer / ".cargo").mkdir()
        (consumer / ".cargo/config.toml").write_text(replacement_config(vendor))
        shutil.copy(RUST / "Cargo.lock", consumer / "Cargo.lock")
    version = tomllib.loads((primitives_dir / "Cargo.toml").read_text())["package"]["version"]
    core = tomllib.loads((primitives_dir / "Cargo.toml").read_text())["dependencies"]["mkit-core"]
    manifest = (consumer / "Cargo.toml").read_text().replace("@VERSION@", version).replace(
        "@CORE@", core["version"])
    (consumer / "Cargo.toml").write_text(manifest)
    (consumer / "src").mkdir(exist_ok=True)
    (consumer / "src/embedded.rs").write_text(embedded_module(consumer / "fixtures"))
    return consumer


def assert_published_style(consumer):
    """Refuse any path dependency, patch table or non-registry mkit package."""
    manifest = tomllib.loads((consumer / "Cargo.toml").read_text())
    tables = [manifest.get("dependencies", {}), manifest.get("dev-dependencies", {})]
    for target in manifest.get("target", {}).values():
        tables += [target.get("dependencies", {}), target.get("dev-dependencies", {})]
    if "patch" in manifest or "replace" in manifest or any(
            isinstance(spec, dict) and ("path" in spec or "git" in spec)
            for table in tables for spec in table.values()):
        raise SystemExit("consumer manifest must not use path/git dependencies or patches")
    lock = tomllib.loads((consumer / "Cargo.lock").read_text())["package"]
    mkit = {p["name"]: p for p in lock if p["name"].startswith("mkit-")}
    if not {"mkit-core", "mkit-primitives"} <= mkit.keys():
        raise SystemExit("consumer lock does not contain the packaged mkit crates")
    for name, package in mkit.items():
        if not package.get("source", "").startswith("registry+"):
            raise SystemExit(f"{name} did not resolve through a registry source")


def run_consumer(consumer, skip_wasm, offline):
    env = dict(os.environ, CARGO_BUILD_JOBS="3", CARGO_INCREMENTAL="0",
               CARGO_TARGET_DIR=str(consumer / "target"))
    lock = []
    if offline:
        # Pin versions to the workspace lock, then require the lock to hold.
        run(["cargo", "metadata", "--offline", "--format-version", "1"], cwd=consumer,
            env=env, stdout=subprocess.DEVNULL)
        lock = ["--locked"]
        assert_published_style(consumer)
    net = ["--offline"] if offline else []
    for features in ([], ["--no-default-features"]):
        run(["cargo", "test", *lock, *net, *features], cwd=consumer, env=env)
    if skip_wasm:
        print("wasm32 run skipped by request", flush=True)
        return
    for features in ([], ["--no-default-features"]):
        run(["wasm-pack", "test", "--node", "--", *lock, *net, *features],
            cwd=consumer, env=env)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--skip-wasm", action="store_true",
                        help="run the native consumer only")
    parser.add_argument("--registry", metavar="VERSION",
                        help="post-publication smoke: resolve this published version from crates.io")
    parser.add_argument("--keep", action="store_true", help="keep the work directory")
    args = parser.parse_args()
    work = Path(tempfile.mkdtemp(prefix="primitives-consumer-"))
    try:
        vendor = work / "vendor"
        vendor.mkdir()
        if args.registry:
            primitives = download_published(args.registry, work)
        else:
            print(f"overlay: {seed_directory_source(vendor)} third-party packages", flush=True)
            extracted = {}
            for name in OVERLAY:
                manifest = RUZSTD_MANIFEST if name == "mkit-ruzstd" else None
                extracted[name] = package(name, manifest, vendor, work)
            primitives = extracted["mkit-primitives"]
        consumer = build_consumer(work, vendor, primitives, bool(args.registry))
        run_consumer(consumer, args.skip_wasm, offline=not args.registry)
        print("primitives consumer: fixtures consumed through the packaged API", flush=True)
    finally:
        if args.keep:
            print(f"work directory kept: {work}")
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        sys.exit(f"primitives consumer failed: {error}")
