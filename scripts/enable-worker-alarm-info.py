#!/usr/bin/env python3
"""Opt a built Worker shim into forwarding runtime alarm metadata."""
# SPDX-License-Identifier: MIT OR Apache-2.0
import argparse
import json
import os
import stat
from pathlib import Path
import tempfile

CLASSES = (
    "RefStore", "NsCoordinator", "RefShard", "RepoIndexShard", "ContentIndexShard"
)
BASE_NAME = "alarm-base.mjs"
MARKER = "// Generated by enable-worker-alarm-info.py; do not edit.\n"


def wrapper_source():
    module = json.dumps("./" + BASE_NAME)
    return (
        MARKER
        + f"import * as base from {module};\n"
        + f"export * from {module};\n"
        + f"export {{ default }} from {module};\n"
        + f"const classes = {json.dumps(CLASSES)}.map(name => {{\n"
        + "  const klass = base[name];\n"
        + "  if (typeof klass !== 'function' || "
        + "typeof klass.prototype.alarmWithInfo !== 'function') {\n"
        + "    throw new Error(`Alarm metadata requires a perf-metrics build: ${name}`);\n"
        + "  }\n"
        + "  return klass;\n"
        + "});\n"
        + "for (const klass of classes) {\n"
        + "  const original = Object.getOwnPropertyDescriptor(klass.prototype, 'alarm');\n"
        + "  Object.defineProperty(klass.prototype, 'alarm', {\n"
        + "    configurable: true, writable: true, enumerable: false, ...original,\n"
        + "    value: function alarm(info) { return this.alarmWithInfo(info); }\n"
        + "  });\n"
        + "}\n"
    )


def enable(shim):
    shim = Path(shim)
    base = shim.with_name(BASE_NAME)
    if shim.name == BASE_NAME:
        raise ValueError("the shim must have a different name from alarm-base.mjs")
    expected = wrapper_source()
    current = shim.read_text()
    if current == expected:
        if not base.is_file():
            raise ValueError("the generated wrapper's base module is missing")
        return
    if current.startswith(MARKER):
        raise ValueError("the existing generated wrapper has unexpected contents")
    if base.exists():
        raise ValueError("alarm-base.mjs already exists; use a fresh build directory")
    temporary = None
    linked = False
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=shim.parent, prefix=".alarm-info-", delete=False
        ) as output:
            temporary = Path(output.name)
            output.write(expected)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(temporary, stat.S_IMODE(shim.stat().st_mode))
        # An exclusive hard link preserves the original bytes and relative imports.
        # Replace only after the base exists: readers never observe a broken shim.
        os.link(shim, base)
        linked = True
        os.replace(temporary, shim)
        temporary = None
    except Exception:
        if linked:
            base.unlink()
        raise
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("shim", type=Path, help="built Worker shim.mjs")
    args = parser.parse_args()
    try:
        enable(args.shim)
    except (OSError, ValueError) as error:
        parser.exit(1, f"alarm metadata wrapper: {error}\n")


if __name__ == "__main__":
    main()
