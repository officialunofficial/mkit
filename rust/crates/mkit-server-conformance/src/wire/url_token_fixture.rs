//! Independent verification of the runner's object URL-token fixture
//! (SPEC-WRITE-GRANTS §3.1, §9.4). This checks protocol bytes, without
//! depending on a server's token implementation or key configuration API.

use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
use ed25519_dalek::{Signature, SigningKey, VerifyingKey};
use mkit_attest::grant::text::{check_lifetime, decimal_millis, decimal_u64, hex32, split_fields};
use mkit_core::hash::{hash, to_hex, to_hex_bytes};
use mkit_core::repo_identity::RepositoryIdentity;
use mkit_core::write_auth::validate_audience;

use super::{URL_TOKEN_SEED, URL_TOKEN_TTL_MS};

/// Verify an object token minted under the runner's dedicated active key.
/// Return its authenticated epoch, which the caller compares with the
/// namespace's current epoch after these stateless checks.
pub(super) fn verify_object_token(
    token: &str,
    audience: &str,
    repository: &str,
    object: &[u8; 32],
    now_ms: i64,
) -> Result<u64, &'static str> {
    let seed = hex32(URL_TOKEN_SEED).expect("the runner's fixed URL-token seed is valid");
    let key = SigningKey::from_bytes(&seed).verifying_key();
    verify(token, audience, repository, object, now_ms, &key)
}

fn verify(
    token: &str,
    audience: &str,
    repository: &str,
    object: &[u8; 32],
    now_ms: i64,
    key: &VerifyingKey,
) -> Result<u64, &'static str> {
    // A 4,096-byte statement plus a 64-byte signature cannot exceed this.
    if token.len() > 8192 {
        return Err("token length");
    }
    let (statement, signature) = token.split_once('.').ok_or("token segments")?;
    let bytes = URL_SAFE_NO_PAD
        .decode(statement)
        .map_err(|_| "statement encoding")?;
    let signature: [u8; 64] = URL_SAFE_NO_PAD
        .decode(signature)
        .map_err(|_| "signature encoding")?
        .try_into()
        .map_err(|_| "signature length")?;
    let fields = split_fields(&bytes, 8).map_err(|_| "canonical statement")?;
    if fields[0] != "mkit-url-token:v1" {
        return Err("statement domain");
    }
    validate_audience(fields[1]).map_err(|_| "audience origin")?;
    RepositoryIdentity::parse_bare_allowed(fields[2]).map_err(|_| "repository identity")?;
    let epoch = decimal_u64(fields[4]).map_err(|_| "epoch encoding")?;
    let issued = decimal_millis(fields[5]).map_err(|_| "issue time")?;
    let expiry = decimal_millis(fields[6]).map_err(|_| "expiry time")?;
    let ttl = i64::try_from(URL_TOKEN_TTL_MS).map_err(|_| "fixture lifetime")?;
    check_lifetime(issued, expiry, ttl).map_err(|_| "token lifetime")?;
    if fields[7] != to_hex_bytes(&hash(key.as_bytes())[..16]) {
        return Err("active key id");
    }
    key.verify_strict(&hash(&bytes), &Signature::from_bytes(&signature))
        .map_err(|_| "signature")?;
    // Exact equality also validates the object target's lowercase hex grammar.
    if fields[1] != audience
        || fields[2] != repository
        || fields[3] != format!("object:{}", to_hex(object))
    {
        return Err("request binding");
    }
    if now_ms >= expiry {
        return Err("expired");
    }
    Ok(epoch)
}

#[cfg(test)]
mod tests {
    use super::*;
    use ed25519_dalek::Signer as _;

    const AUDIENCE: &str = "https://api.example.test";
    const REPOSITORY: &str =
        "ed25519-ea4a6c63e29c520abef5507b132ec5f9954776aebebe7b92421eea691446d22c/room-a";
    const NOW: i64 = 1_700_000_000_000;

    fn key() -> SigningKey {
        SigningKey::from_bytes(&hex32(URL_TOKEN_SEED).expect("fixture seed"))
    }

    fn fields() -> Vec<String> {
        vec![
            "mkit-url-token:v1".into(),
            AUDIENCE.into(),
            REPOSITORY.into(),
            format!("object:{}", to_hex(&[0xaa; 32])),
            "0".into(),
            NOW.to_string(),
            (NOW + 900_000).to_string(),
            to_hex_bytes(&hash(key().verifying_key().as_bytes())[..16]),
        ]
    }

    fn signed(statement: &str, key: &SigningKey) -> String {
        format!(
            "{}.{}",
            URL_SAFE_NO_PAD.encode(statement),
            URL_SAFE_NO_PAD.encode(key.sign(&hash(statement.as_bytes())).to_bytes())
        )
    }

    fn check(token: &str) -> Result<u64, &'static str> {
        verify_object_token(token, AUDIENCE, REPOSITORY, &[0xaa; 32], NOW)
    }

    #[test]
    fn independently_generated_golden_signature_verifies() {
        // SPEC-WRITE-GRANTS §9.4's object-epoch-0 vector, generated by the
        // independent Python fixture generator. Keep it self-contained so
        // the published crate's tests need no workspace fixture files.
        let golden_key = SigningKey::from_bytes(&[9; 32]).verifying_key();
        let mut f = fields();
        f[7] = "8fd4250c7e19a226bb17ae00d988b536".into();
        let token = format!(
            "{}.SEZNWIr74g82H2gmgrDmD3COW9xERzVyUckUpSd9aJWC6Qoe7hGOzybSJ_0g0vK9f9t_OAaSAftmJk6UitLuDw",
            URL_SAFE_NO_PAD.encode(f.join("\n"))
        );
        assert_eq!(
            verify(&token, AUDIENCE, REPOSITORY, &[0xaa; 32], NOW, &golden_key),
            Ok(0)
        );
        assert_eq!(check(&token), Err("active key id"));
    }

    #[test]
    fn fixture_authenticates_epoch_and_exact_request_binding() {
        let mut f = fields();
        f[4] = u64::MAX.to_string();
        let token = signed(&f.join("\n"), &key());
        assert_eq!(check(&token), Ok(u64::MAX));
        assert!(
            verify_object_token(
                &token,
                "https://other.example.test",
                REPOSITORY,
                &[0xaa; 32],
                NOW
            )
            .is_err()
        );
        assert!(verify_object_token(&token, AUDIENCE, "other", &[0xaa; 32], NOW).is_err());
        assert!(verify_object_token(&token, AUDIENCE, REPOSITORY, &[0xbb; 32], NOW).is_err());
        assert_eq!(
            verify_object_token(&token, AUDIENCE, REPOSITORY, &[0xaa; 32], NOW + 900_000),
            Err("expired")
        );
    }

    #[test]
    fn refuses_signed_noncanonical_or_misbound_statements() {
        for (index, replacement) in [
            (0, "another-domain"),
            (1, "https://api.example.test/"),
            (2, "invalid/repository/path"),
            (
                3,
                "object:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA",
            ),
            (4, "00"),
            (4, "18446744073709551616"),
            (5, "-1"),
            (5, "9223372036854775808"),
            (6, "1700000000000"),
            (6, "1700000900001"),
            (7, "8FD4250C7E19A226BB17AE00D988B536"),
        ] {
            let mut f = fields();
            f[index] = replacement.into();
            assert!(
                check(&signed(&f.join("\n"), &key())).is_err(),
                "field {index}"
            );
        }
        let statement = fields().join("\n");
        for invalid in [
            format!("{statement}\n"),
            statement.replace('\n', "\r\n"),
            format!("{statement}\nextra"),
        ] {
            assert!(check(&signed(&invalid, &key())).is_err());
        }
    }

    #[test]
    fn refuses_noncanonical_token_encoding_and_foreign_signature() {
        let token = signed(&fields().join("\n"), &key());
        assert_eq!(check(&token), Ok(0));
        let (statement, signature) = token.split_once('.').expect("token segments");
        for invalid in [
            format!("{statement}=.{signature}"),
            format!("{statement}.{signature}="),
            format!("{token}.extra"),
            format!("{statement}.+{signature}"),
            format!(".{signature}"),
            format!("{statement}."),
        ] {
            assert!(check(&invalid).is_err());
        }
        // A 64-byte signature has four unused bits in its last base64 digit.
        let alphabet = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
        let mut invalid = token.into_bytes();
        let last = invalid.last_mut().expect("nonempty token");
        let index = alphabet
            .iter()
            .position(|b| b == last)
            .expect("base64 digit");
        *last = alphabet[index + 1];
        assert!(check(&String::from_utf8(invalid).expect("ASCII token")).is_err());
        assert_eq!(
            check(&signed(
                &fields().join("\n"),
                &SigningKey::from_bytes(&[8; 32])
            )),
            Err("signature")
        );
    }
}
